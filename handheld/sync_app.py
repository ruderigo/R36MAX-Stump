#!/usr/bin/env python3
"""Writes src/engine/stumpNativeCode.ts from the files in handheld/, so the
web app shows and offers exactly what install.sh installs.

    python3 handheld/sync_app.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "src", "engine", "stumpNativeCode.ts")

# (export name, file, id, language, title, summary)
FILES = [
    ("STUMP_R36MAX_C_SOURCE", "stump_r36max_engine.c", "stump_r36max_c", "c",
     "Cockpit engine v2.0.0-r36max (720x720, gamepad, QR)",
     "The handheld's screen and gamepad: five panels (chats, board, files, network, setup). Reads "
     "/dev/shm/stump_live.txt and sends command lines to cockpit_feed.py; never touches the Stump's "
     "files or the network. The v1.8.8 KMSDRM display fixes are kept."),
    ("STUMP_R36MAX_BRIDGE_PY", "cockpit_feed.py", "cockpit_feed_py", "python",
     "cockpit_feed.py: the cockpit's client of the Stump",
     "Replaces the 161 KB run_stump_r36max.py bridge. Talks to the stock PC Stump over its public HTTP "
     "API (/rrc/poll, /rrc/send, /post, /upload, /admin deletes, /chain.json), like the web chat or "
     "FireFly; hotspot and Wi-Fi through NetworkManager. Standard library only."),
    ("STUMP_R36MAX_PORTS_SCRIPT", "LaBuche_Stump.sh", "labuche_stump_sh", "bash",
     "EmulationStation Ports launcher v2.0.0-r36max (/roms/ports/LaBuche_Stump.sh)",
     "Opens the cockpit on the Stump that runs in the background from boot; SELECT+START returns to "
     "EmulationStation and the Stump keeps running. No firewall flush, no NetworkManager masking."),
    ("STUMP_R36MAX_INSTALL_SH", "install.sh", "install_sh", "bash",
     "install.sh: makes the R36MAX a Stump like any other",
     "Clones SandBox_Stump_On, runs its provisioner.py --pc (the same wizard and service as every "
     "computer Stump), gives the Stump's own Python ports 80/53, builds the cockpit, installs the "
     "launcher, and puts the old v1.x bridge aside."),
    ("STUMP_R36MAX_DISPLAY_PY", "stump_pygame_display.py", "stump_pygame_display_py", "python",
     "stump_pygame_display.py: KMSDRM presenter (from v1.8.8, unchanged)",
     "pygame KMSDRM display that presents /dev/shm/stump_fb.rgba and watches SELECT+START."),
]


def ts_template(text):
    return text.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")


def main():
    out = ["/**\n * GENERATED by handheld/sync_app.py from handheld/: edit those files, then run it.\n"
           " *\n * The R36MAX runs the stock PC Stump (SandBox_Stump_On pc/stump_pc.py, set up by\n"
           " * provisioner.py --pc); these are the handheld's own pieces around it.\n */\n\n"
           "import { CodeFileArtifact } from './nativeEngineCode';\n\n"]
    for name, fname, *_ in FILES:
        with open(os.path.join(HERE, fname), encoding="utf-8") as f:
            out.append("export const %s = `%s`;\n\n" % (name, ts_template(f.read())))
    out.append("export const STUMP_CODE_ARTIFACTS: CodeFileArtifact[] = [\n")
    for name, fname, aid, lang, title, summary in FILES:
        out.append("  {\n    id: %r,\n    filename: %r,\n    title: %r,\n    language: %r,\n    summary:\n      %r,\n"
                   "    content: %s,\n  },\n" % (aid, fname, title, lang, summary, name))
    out.append("];\n")
    text = "".join(out).replace("\r\n", "\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d KB)" % (OUT, len(text) // 1024))


if __name__ == "__main__":
    main()
